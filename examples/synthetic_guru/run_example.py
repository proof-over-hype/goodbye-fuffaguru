"""A strategy that looks like a winner but does not beat chance.

Everything here is synthetic: the market is a random walk generated by the
code, so no rule can have a real edge on it. The story:

1. A fictional guru tries many variants of a "fade the level" method on a
   couple of months of data and keeps the best one (data snooping).
2. He shows only his nicest trades and counts "winning days", not trades.
3. We write his rules down, freeze them with a fingerprint, and run the
   checks: random direction at the same instants, fake levels, the number of
   variants tried, and a confirmation period he never saw.

Run:  python examples/synthetic_guru/run_example.py  [--quick] [--out DIR]
"""

from __future__ import annotations

import argparse
import itertools
import sys
from pathlib import Path

import numpy as np
import pandas as pd

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parents[1]))  # allow running without installing the package

from fuffaguru.metrics import summarize_r, win_rate_by_days  # noqa: E402
from fuffaguru.nulltests import fake_levels_test, random_direction_test  # noqa: E402
from fuffaguru.prereg import fingerprint, freeze_recipe, log_trial  # noqa: E402
from fuffaguru.recipes import LevelRecipe, swing_levels  # noqa: E402
from fuffaguru.report import Claims, reality_check  # noqa: E402
from fuffaguru.synthetic import random_walk_bars  # noqa: E402

COST = 0.25  # round trip in price units (spread + commission), about 0.06 ATR
GRID = {
    "stop_atr": [0.5, 1.0, 1.5, 2.0],
    "target_r": [1.0, 2.0, 3.0],
    "breakeven_at_r": [None, 0.5],
    "trend_bars": [None, 200],
}


def mean_net(recipe: LevelRecipe, bars, levels, prices=None) -> float:
    res = recipe.run(bars, levels, prices)
    return float(res["net_r"].mean()) if len(res) else float("nan")


def run(out_dir: Path, quick: bool = False, seed: int = 7, verbose: bool = True) -> dict:
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    say = print if verbose else (lambda *a, **k: None)

    n_dev = 5000 if quick else 6000          # 15-minute bars: about two months
    n_conf = 3 * n_dev                        # a longer period the guru never saw
    dev = random_walk_bars(n_dev, seed=seed, start="2024-01-01")
    conf = random_walk_bars(n_conf, seed=seed + 1, start=str(dev.index[-1] + pd.Timedelta("15min")),
                            start_price=float(dev["close"].iloc[-1]))
    lv_dev = swing_levels(dev, k=5)
    lv_conf = swing_levels(conf, k=5)

    # 1. The guru's backtest: try every variant, keep the best (data snooping).
    trials = out_dir / "trials.jsonl"
    if trials.exists():
        trials.unlink()
    scores = []
    for values in itertools.product(*GRID.values()):
        recipe = LevelRecipe(cost=COST, **dict(zip(GRID.keys(), values)))
        score = mean_net(recipe, dev, lv_dev)
        log_trial(trials, fingerprint(recipe.to_dict()), "dev mean net R", {"mean_net_r": score})
        scores.append((score, recipe))
    n_trials = len(scores)
    best_score, best = max(scores, key=lambda x: (x[0] if not np.isnan(x[0]) else -9))
    dev_res = best.run(dev, lv_dev)
    s = summarize_r(dev_res["net_r"])
    days = win_rate_by_days(dev_res["entry_time"], dev_res["net_r"])
    say(f"Variants tried: {n_trials}. Best: {best.to_dict()}")
    say(f"  in sample: {s['n']} trades, mean {s['mean']:+.3f} R after costs, win rate {s['win_rate']:.0%}")

    # 2. The marketing: the nicest trades and the 'winning days'.
    showcase = dev_res.sort_values("net_r", ascending=False).head(12)
    showcase = pd.concat([showcase, dev_res[dev_res["net_r"] < 0].head(1)])
    shown_wins = int((showcase["net_r"] > 0).sum())
    claimed = days["non_negative_day_rate"]
    say(f"  shown: {shown_wins} winners out of {len(showcase)} examples; 'days without a loss': {claimed:.0%}")

    # 3. Preregistration of the guru's rules as we understood them.
    recipe_doc = {
        "name": "synthetic guru - fade the first return to a swing level",
        "source": "synthetic example, no real trader",
        "hypothesis": "Fading the first return to an untouched swing level makes money after costs.",
        "rules": best.to_dict() | {"levels": "swing highs/lows, 5 bars each side, confirmed after 5 bars"},
        "data": {"development": "synthetic 15-minute bars", "confirmation": "new synthetic bars, 3x longer"},
        "costs": {"round_trip_price": COST},
        "controls": ["random direction at the same instants", "fake levels shifted by 0.5-3 ATR",
                     f"{n_trials} variants tried: adjust p-values", "confirmation period"],
        "closing_rules": [
            "Dead if the mean result after costs in the confirmation period is not above zero.",
            "Dead if it does not beat random direction at the same instants (p <= 0.05 after adjustment).",
            "Dead if real levels do not beat fake levels (p <= 0.05).",
            "No change of any parameter after seeing the numbers.",
        ],
    }
    frozen = freeze_recipe(recipe_doc, out_dir / "recipe.frozen.json", overwrite=True)
    say(f"  frozen with sha256 {frozen['frozen']['sha256'][:16]}...")

    # 4. The checks.
    sims = 40 if quick else 100
    fake_dev = fake_levels_test(lambda p: mean_net(best, dev, lv_dev, p), lv_dev["price"], lv_dev["scale"],
                                n_sims=sims, seed=1)
    conf_res = best.run(conf, lv_conf)
    rd_conf = random_direction_test(conf_res["net_r"], conf_res["flipped_net_r"], seed=2)
    fake_conf = fake_levels_test(lambda p: mean_net(best, conf, lv_conf, p), lv_conf["price"], lv_conf["scale"],
                                 n_sims=sims // 2, seed=3)
    confirmation = {"n": len(conf_res), "mean": float(conf_res["net_r"].mean()),
                    "p_random_direction": rd_conf.p_value, "fake_levels_p": fake_conf.p_value}
    say(f"  confirmation: {confirmation['n']} trades, mean {confirmation['mean']:+.3f} R")

    rc = reality_check(
        dev_res,
        title="Reality Check - synthetic guru (example)",
        claims=Claims(win_rate=claimed, win_rate_basis="days", other=[
            f"Shows {shown_wins} winning trades out of {len(showcase)} examples (picked after the fact)."]),
        extra_nulls=[fake_dev],
        confirmation=confirmation,
        n_trials=n_trials,
        notes=[
            "Synthetic random-walk market: no rule can have a real edge here, by construction.",
            f"The rules tested are the best of {n_trials} variants chosen on the development period.",
            f"Recipe fingerprint (sha256): {frozen['frozen']['sha256']}.",
        ],
    )
    path = rc.write(out_dir / "REALITY_CHECK.md")
    say(f"Verdict: {rc.verdict}\nReport: {path}")
    return {"verdict": rc.verdict, "best_score": best_score, "dev_summary": s, "confirmation": confirmation,
            "n_trials": n_trials, "report": path, "claimed_days": claimed, "shown_wins": shown_wins}


def main(argv=None) -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", default=str(HERE / "output"), help="output folder (ignored by git)")
    ap.add_argument("--quick", action="store_true", help="smaller data, faster")
    ap.add_argument("--seed", type=int, default=7)
    args = ap.parse_args(argv)
    run(Path(args.out), quick=args.quick, seed=args.seed)


if __name__ == "__main__":
    main()
